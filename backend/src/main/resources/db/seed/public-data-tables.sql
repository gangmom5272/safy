-- 공공데이터 수집 파이프라인 테이블 5개를 생성합니다.
--
-- 왜 필요한가:
--   local·dev 는 ddl-auto: update 로 엔티티에서 테이블이 자동 생성되지만,
--   prod 는 ddl-auto: validate 이므로 테이블이 미리 존재해야 애플리케이션이 뜹니다.
--   Flyway 같은 마이그레이션 도구가 아직 없어 배포 전에 수동 실행합니다.
--
-- 실행:
--   docker exec -i backend-db-1 psql -U <DB_USER> -d <DB_NAME> \
--     < backend/src/main/resources/db/seed/public-data-tables.sql
--
-- 모두 IF NOT EXISTS 이므로 여러 번 실행해도 됩니다.
-- 엔티티의 컬럼을 바꿀 때마다 이 파일도 함께 갱신하세요.
--
-- 주의: ddl-auto: update 는 이미 만들어진 컬럼의 타입·NULL 여부를 바꾸지도,
--   불필요해진 인덱스를 지우지도, NOT NULL 컬럼을 추가하지도 못합니다.
--   이 다섯 테이블이 처음 만들어진 뒤 다음이 바뀌었습니다:
--     - 상류 자유 텍스트 컬럼이 varchar 에서 text 로 넓어졌습니다.
--     - places.category 가 추가되었습니다(NOT NULL).
--     - places.center_latitude·center_longitude 가 NULL 허용으로 바뀌었습니다.
--     - places.boundary_geojson 이 추가되었습니다.
--     - places.address 가 제거되었습니다(채울 소스가 없고 아무도 읽지 않던 컬럼).
--   이전 버전으로 local·dev DB 를 한 번이라도 띄웠다면 다섯 테이블을 DROP 하고 다시 만드세요.
--   (아직 어디에도 실제 데이터가 적재되지 않은 상태라 안전합니다.)

-- 서울시 실시간 도시데이터가 다루는 주요 지역. 정적 마스터 데이터입니다.
CREATE TABLE IF NOT EXISTS places (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_place_id VARCHAR(255)             NOT NULL,
    name              VARCHAR(255)             NOT NULL,
    category          VARCHAR(30)              NOT NULL,
    -- 좌표는 지도 표시에만 쓰이고 수집에는 필요하지 않습니다.
    -- 서울시 121장소 목록에 좌표가 없어 지오코딩·검수를 거쳐 나중에 채우므로 NULL 을 허용합니다.
    center_latitude   NUMERIC(10, 7),
    center_longitude  NUMERIC(10, 7),
    -- 지역 영역의 GeoJSON Polygon. 제보 좌표가 어느 지역 안인지 판정하는 데 씁니다.
    -- administrative_areas.boundary_geojson 과 같이 text 입니다(H2 가 jsonb 리터럴을 받지 못함).
    boundary_geojson  TEXT,
    source            VARCHAR(50),
    is_active         BOOLEAN                  NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_places_external_place_id UNIQUE (external_place_id)
);

-- FastAPI 서버가 공공데이터 원본 API 를 호출한 실행 이력.
-- external_run_id 유일 제약이 같은 실행의 중복 적재를 막는 유일한 근거입니다.
CREATE TABLE IF NOT EXISTS data_collection_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_run_id VARCHAR(100)                NOT NULL,
    job_type        VARCHAR(50)                 NOT NULL,
    source          VARCHAR(50)                 NOT NULL,
    started_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    finished_at     TIMESTAMP(6) WITH TIME ZONE,
    status          VARCHAR(30)                 NOT NULL,
    success_count   INTEGER,
    failure_count   INTEGER,
    error_code      VARCHAR(100),
    error_message   TEXT,
    error_details   JSONB,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_data_collection_runs_external_run_id UNIQUE (external_run_id)
);

-- 지역별 인구 밀집 관측값. 추가만 하고 수정하지 않습니다.
CREATE TABLE IF NOT EXISTS city_congestion_observations (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id           BIGINT                      NOT NULL,
    collection_run_id  BIGINT                      NOT NULL,
    area_code          VARCHAR(100)                NOT NULL,
    area_name          TEXT                        NOT NULL,
    -- 좌표는 두지 않습니다. 원본 인구 블록이 지역 좌표를 주지 않고,
    -- 지역 중심점은 지역당 하나뿐이라 places 가 갖는 값입니다.
    congestion_level   VARCHAR(30)                 NOT NULL,
    congestion_message TEXT,
    population_min     INTEGER,
    population_max     INTEGER,
    observed_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    collected_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source             VARCHAR(50)                 NOT NULL,
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- 이 유일 제약이 만드는 btree 인덱스가 지역별 최신 1건 조회(역방향 스캔)와
    -- 추이 조회를 함께 담당하므로, 같은 컬럼 조합의 별도 인덱스는 두지 않습니다.
    CONSTRAINT uk_city_congestion_observations_place_observed_at UNIQUE (place_id, observed_at),
    CONSTRAINT fk_city_congestion_observations_place
        FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_city_congestion_observations_collection_run
        FOREIGN KEY (collection_run_id) REFERENCES data_collection_runs (id)
);

-- 서울시 문화 행사. citydata 응답의 EVENT_STTS 에서 수집합니다.
CREATE TABLE IF NOT EXISTS events (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    place_id          BIGINT                      NOT NULL,
    collection_run_id BIGINT                      NOT NULL,
    external_id       VARCHAR(255)                NOT NULL,
    -- 상류 자유 텍스트는 길이를 제한하지 않습니다.
    -- varchar 를 넘기면 INSERT 가 실패해 그 수집 배치 전체가 롤백됩니다.
    title             TEXT                        NOT NULL,
    description       TEXT,
    venue_name        TEXT,
    event_period      TEXT,
    start_date        DATE,
    end_date          DATE,
    latitude          NUMERIC(10, 7),
    longitude         NUMERIC(10, 7),
    area_code         VARCHAR(100),
    area_name         TEXT,
    is_paid           BOOLEAN,
    thumbnail_url     TEXT,
    detail_url        TEXT,
    source            VARCHAR(50)                 NOT NULL,
    collected_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_events_source_external_id UNIQUE (source, external_id),
    CONSTRAINT fk_events_place FOREIGN KEY (place_id) REFERENCES places (id),
    CONSTRAINT fk_events_collection_run
        FOREIGN KEY (collection_run_id) REFERENCES data_collection_runs (id)
);

CREATE INDEX IF NOT EXISTS idx_events_start_date_end_date
    ON events (start_date, end_date);

-- 긴급 재난 문자. 원본 API 가 좌표를 주지 않으므로 위치는 regions 로만 표현됩니다.
CREATE TABLE IF NOT EXISTS disaster_messages (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection_run_id BIGINT                      NOT NULL,
    external_id       VARCHAR(255)                NOT NULL,
    message           TEXT                        NOT NULL,
    regions           JSONB                       NOT NULL,
    disaster_type     TEXT,
    emergency_level   TEXT                        NOT NULL,
    sent_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source            VARCHAR(50)                 NOT NULL,
    collected_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_disaster_messages_source_external_id UNIQUE (source, external_id),
    CONSTRAINT fk_disaster_messages_collection_run
        FOREIGN KEY (collection_run_id) REFERENCES data_collection_runs (id)
);

CREATE INDEX IF NOT EXISTS idx_disaster_messages_sent_at
    ON disaster_messages (sent_at DESC);
