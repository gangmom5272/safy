-- prod 프로필은 ddl-auto=validate이므로 최초 배포 전에 PostgreSQL에 한 번 적용한다.
-- dev 프로필은 Hibernate ddl-auto=update가 동일한 테이블과 인덱스를 생성한다.

create table if not exists notifications (
    id bigint generated by default as identity primary key,
    recipient_user_id bigint not null,
    type varchar(20) not null,
    title varchar(120) not null,
    content text not null,
    report_id bigint,
    source_event_id bigint not null,
    read_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_notifications_source_event unique (source_event_id)
);

create index if not exists idx_notifications_recipient_created
    on notifications (recipient_user_id, created_at);

alter table notifications
    add column if not exists area_report_request_id bigint;

create table if not exists notification_settings (
    user_id bigint primary key,
    enabled boolean not null,
    report_enabled boolean not null,
    safety_enabled boolean not null,
    system_enabled boolean not null,
    saved_location_enabled boolean not null,
    location_request_enabled boolean not null default false,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

alter table notification_settings
    add column if not exists location_request_enabled boolean not null default false;

create table if not exists web_push_subscriptions (
    id bigint generated by default as identity primary key,
    recipient_user_id bigint not null,
    endpoint varchar(2048) not null,
    endpoint_hash varchar(64) not null,
    p256dh varchar(255) not null,
    auth varchar(255) not null,
    user_agent varchar(512),
    status varchar(20) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_web_push_endpoint_hash unique (endpoint_hash)
);

create index if not exists idx_web_push_recipient_status
    on web_push_subscriptions (recipient_user_id, status);

create table if not exists notification_push_delivery_jobs (
    id bigint generated by default as identity primary key,
    version bigint not null,
    notification_id bigint not null,
    subscription_id bigint not null,
    status varchar(20) not null,
    attempt_count integer not null,
    next_attempt_at timestamp(6) with time zone,
    last_error text,
    started_at timestamp(6) with time zone,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint uk_notification_push_jobs_target unique (notification_id, subscription_id)
);

create index if not exists idx_notification_push_jobs_ready
    on notification_push_delivery_jobs (status, next_attempt_at);

create table if not exists user_location_presences (
    user_id bigint primary key,
    latitude numeric(10, 7) not null,
    longitude numeric(10, 7) not null,
    grid_cell_code varchar(24) not null,
    place_id bigint,
    last_location_at timestamp(6) with time zone not null,
    last_seen_at timestamp(6) with time zone not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create index if not exists idx_user_location_presence_target
    on user_location_presences (place_id, last_location_at, last_seen_at);

create table if not exists area_report_requests (
    id bigint generated by default as identity primary key,
    requester_user_id bigint not null,
    place_id bigint not null,
    place_name varchar(255) not null,
    title varchar(120) not null,
    content varchar(500) not null,
    requested_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    recipient_count integer not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create index if not exists idx_area_report_requests_place_created
    on area_report_requests (place_id, created_at);
