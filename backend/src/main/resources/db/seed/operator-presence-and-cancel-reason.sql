-- 배정 에스컬레이션(담당자 근무 상태 · 배정 취소 사유) 도입에 필요한 스키마입니다.
--
-- 왜 필요한가:
--   prod 프로파일은 ddl-auto: validate 라(application-prod.yml) Hibernate 가 새 테이블·컬럼을
--   만들어주지 않습니다. 이 스크립트를 먼저 실행하지 않으면 배포 시 스키마 검증에 실패해
--   애플리케이션이 기동하지 못합니다.
--   dev/local(ddl-auto: update)은 Hibernate 가 자동으로 만들어주므로 실행하지 않아도 됩니다.
--
-- 실행:
--   docker exec -i backend-db-1 psql -U <DB_USER> -d <DB_NAME> \
--     < backend/src/main/resources/db/seed/operator-presence-and-cancel-reason.sql
--
-- 여러 번 실행해도 안전합니다.

-- 담당자 근무 상태. 자동 배정은 ON_DUTY 인 담당자에게만 이루어지고,
-- 연결이 끊긴 채 유예가 지나면 스위퍼가 OFFLINE 으로 내리며 배정을 회수합니다.
CREATE TABLE IF NOT EXISTS operator_presences (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id  bigint                      NOT NULL,
    status       varchar(30)                 NOT NULL,
    last_seen_at timestamp(6) with time zone NOT NULL,
    created_at   timestamp(6) with time zone NOT NULL,
    updated_at   timestamp(6) with time zone NOT NULL,
    CONSTRAINT uk_operator_presences_operator UNIQUE (operator_id)
);

-- 배정이 CANCELLED 로 끝난 사유. 자동 배정의 되돌아옴 방지(제외 목록)는 담당자가 스스로
-- 놓아준 사유(REASSIGN_REQUESTED/TRANSFERRED)만 대상으로 하므로, 이 값이 없으면
-- 무응답 회수까지 영구 제외되어 자동 배정이 고사합니다.
ALTER TABLE report_operator_assignments
    ADD COLUMN IF NOT EXISTS cancel_reason varchar(30);

-- 참고: status / cancel_reason 의 CHECK 제약은 두지 않았습니다.
--   ddl-auto 는 기존 CHECK 제약을 수정하지 않아, enum 에 값이 추가되면 제약만 옛 상태로 남아
--   INSERT 가 통째로 막히는 사고가 이미 한 번 있었습니다
--   (realtime-event-type-constraint.sql 참고). 값 검증은 애플리케이션 enum 이 담당합니다.
